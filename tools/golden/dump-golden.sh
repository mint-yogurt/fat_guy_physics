#!/usr/bin/env bash
# Regenerates tools/golden/golden.json from the C++ implementation.
#
# Run this only when the C++ reference behaviour deliberately changes. The
# committed golden.json is what packages/shared's tests assert against, so
# regenerating it to make a failing test pass defeats the point -- if a test
# fails, the TypeScript is wrong until proven otherwise.
#
# Needs a C++17 compiler on PATH (g++ or clang++). No CMake, no GL, no Jolt:
# the dumper compiles only the four pure voxel translation units.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "$here/../.." && pwd)"

glm="$repo/build/_deps/glm-src"
if [[ ! -d "$glm/glm" ]]; then
  echo "glm headers not found at $glm" >&2
  echo "run 'cmake -B build' once to fetch dependencies, then retry" >&2
  exit 1
fi

# hash32/hashFloat live in an anonymous namespace inside Vegetation.cpp, so
# they cannot be linked against. Extract them verbatim rather than copying
# them by hand: a hand copy could drift from the original, and a golden test
# built on a drifted copy is worse than no golden test at all.
extracted="$here/hash_extracted.inc"
{
  echo "// GENERATED by dump-golden.sh from src/voxel/Vegetation.cpp -- do not edit."
  sed -n '/^std::uint32_t hash32/,/^}/p' "$repo/src/voxel/Vegetation.cpp"
  sed -n '/^float hashFloat/,/^}/p' "$repo/src/voxel/Vegetation.cpp"
} > "$extracted"

if ! grep -q '0x01000193u' "$extracted"; then
  echo "extraction from Vegetation.cpp failed (FNV prime not found)" >&2
  echo "the function signatures there probably changed; fix the sed ranges" >&2
  exit 1
fi

# Collision.cpp and Player.cpp reach World through a three-method surface,
# but the real World.hpp drags in OpenGL, Vegetation and a thread pool. Stage
# the two UNMODIFIED sources in a scratch directory alongside a stub
# World.hpp (tools/golden/stub/World.hpp), so the compiler's quoted-include
# lookup -- which checks the including file's own directory first -- resolves
# to the stub. The behaviour under test is the real code; only the terrain
# storage around it is simplified.
stage="$here/.stage"
rm -rf "$stage"
mkdir -p "$stage/voxel"
cp "$repo/src/voxel/Collision.cpp" "$repo/src/voxel/Collision.hpp" "$stage/"
cp "$repo/src/Player.cpp" "$repo/src/Player.hpp" "$stage/"
cp "$here/stub/World.hpp" "$stage/"
# Player.cpp includes its headers as "voxel/Collision.hpp" and friends, so
# mirror that layout -- as one-line forwarding shims rather than copies,
# because two copies of the same header at different paths each satisfy
# their own #pragma once and redefine everything in them.
for header in Collision.hpp World.hpp; do
  printf '#pragma once\n#include "../%s"\n' "$header" > "$stage/voxel/$header"
done
# Everything else (Voxel.hpp, Chunk.hpp, TerrainGenerator.hpp) is NOT staged:
# it resolves to the real headers via -I below, so the dumper and the staged
# sources agree on one definition of each.

cxx="${CXX:-g++}"
out="$here/dump_golden.exe"

echo "compiling with $cxx ..."
"$cxx" -std=c++20 -O1 -o "$out" \
  "$here/dump_golden.cpp" \
  "$stage/Collision.cpp" \
  "$stage/Player.cpp" \
  "$repo/src/voxel/Voxel.cpp" \
  "$repo/src/voxel/ChunkMesher.cpp" \
  "$repo/src/voxel/TerrainGenerator.cpp" \
  -I"$stage" \
  -I"$repo/src" \
  -I"$repo/src/voxel" \
  -I"$glm" \
  -I"$repo/third_party/fastnoiselite"

echo "running ..."
"$out" "$here/golden.json"
echo "golden.json updated"
